// Generates src/lib/tradChars.ts: a per-character 简→繁 map covering every term
// collectTerms() finds, derived from OpenCC (cn → t). Run: npm run gen:trad
import { writeFileSync } from 'node:fs'
import { TRAD_TERMS } from '../src/lib/tradOverrides'
import { expectedTrad } from './opencc'
import { collectTerms } from './terms'

const map = new Map<string, { to: string; term: string }>()
const conflicts: string[] = []
const terms = collectTerms([1900, 2100])
for (const term of terms) {
  if (TRAD_TERMS[term]) continue // handled whole, not per character
  const src = [...term]
  const dst = [...expectedTrad(term)]
  if (src.length !== dst.length) throw new Error(`length changed: ${term} → ${dst.join('')}`)
  src.forEach((c, i) => {
    // Record unchanged characters too, so 天干 (干 stays) vs 幹 shows up as a conflict.
    const prev = map.get(c)
    if (prev && prev.to !== dst[i]) conflicts.push(`${c}: ${prev.to} (${prev.term}) / ${dst[i]} (${term})`)
    else if (!prev) map.set(c, { to: dst[i], term })
  })
}
if (conflicts.length) {
  console.error('Ambiguous characters; add them to TRAD_OVERRIDES:\n' + conflicts.join('\n'))
  process.exit(1)
}

const entries = [...map]
  .filter(([s, { to }]) => s !== to)
  .map(([s, { to }]) => [s, to] as const)
  .sort(([a], [b]) => a.localeCompare(b, 'zh'))
writeFileSync(
  'src/lib/tradChars.ts',
  `// Generated by scripts/gen-trad.ts from OpenCC (cn → t) over ${terms.length} terms. Do not edit by hand.\n` +
    `export const TRAD_CHARS: Record<string, string> = {\n` +
    entries.map(([s, t]) => `  '${s}': '${t}',`).join('\n') +
    `\n}\n`,
)
console.log(`${terms.length} terms, ${entries.length} characters`)
